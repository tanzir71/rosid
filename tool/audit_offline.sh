#!/usr/bin/env bash
set -euo pipefail

PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SOURCE_MANIFEST="$PROJECT_DIR/android/app/src/main/AndroidManifest.xml"
DATA_EXTRACTION_RULES="$PROJECT_DIR/android/app/src/main/res/xml/data_extraction_rules.xml"
REQUIRE_MERGED="${ROSID_REQUIRE_MERGED_MANIFEST:-0}"

for argument in "$@"; do
  case "$argument" in
    --require-merged) REQUIRE_MERGED=1 ;;
    *)
      echo "Unknown argument: $argument" >&2
      exit 2
      ;;
  esac
done

# Tag releases and an existing release APK must never pass a source-only audit.
if [[ "${GITHUB_REF_TYPE:-}" == "tag" ]] ||
  [[ -f "$PROJECT_DIR/build/app/outputs/flutter-apk/app-release.apk" ]]; then
  REQUIRE_MERGED=1
fi

extract_permissions() {
  local manifest="$1"
  awk '
    BEGIN { RS = ">" }
    /<uses-permission(-sdk-[0-9]+)?/ && !/tools:node="remove"/ {
      if (match($0, /android:name="[^"]+"/)) {
        permission = substr($0, RSTART, RLENGTH)
        sub(/^android:name="/, "", permission)
        sub(/"$/, "", permission)
        print permission
      }
    }
  ' "$manifest" | sort -u
}

audit_manifest_permissions() {
  local manifest="$1"
  local label="$2"
  local permission
  local camera_found=0
  local rejected=0

  if [[ ! -s "$manifest" ]] || ! rg --quiet '<manifest\b' "$manifest"; then
    echo "$label manifest is missing or invalid: $manifest" >&2
    return 1
  fi

  while IFS= read -r permission; do
    [[ -z "$permission" ]] && continue
    case "$permission" in
      android.permission.CAMERA)
        camera_found=1
        ;;
      android.permission.READ_MEDIA_IMAGES)
        # Optional gallery access allowed by the product privacy policy.
        ;;
      app.rosid.rosid.DYNAMIC_RECEIVER_NOT_EXPORTED_PERMISSION)
        # Signature-only compatibility permission generated by AndroidX Core.
        ;;
      *)
        echo "Disallowed permission in $label manifest: $permission" >&2
        rejected=1
        ;;
    esac
  done < <(extract_permissions "$manifest")

  if [[ "$camera_found" -ne 1 ]]; then
    echo "Required CAMERA permission missing from $label manifest: $manifest" >&2
    rejected=1
  fi
  return "$rejected"
}

audit_manifest_backup_policy() {
  local manifest="$1"
  local label="$2"
  if ! rg --quiet 'android:allowBackup="false"' "$manifest" ||
    ! rg --quiet 'android:fullBackupContent="false"' "$manifest" ||
    ! rg --quiet 'android:dataExtractionRules="@xml/data_extraction_rules"' "$manifest"; then
    echo "Android backup/data-extraction protection is incomplete in $label manifest." >&2
    return 1
  fi
}

audit_manifest_permissions "$SOURCE_MANIFEST" "Android source"
audit_manifest_backup_policy "$SOURCE_MANIFEST" "Android source"

if [[ ! -s "$DATA_EXTRACTION_RULES" ]] ||
  ! rg --quiet '<cloud-backup>' "$DATA_EXTRACTION_RULES" ||
  ! rg --quiet '<device-transfer>' "$DATA_EXTRACTION_RULES"; then
  echo "Android data extraction rules are missing or incomplete." >&2
  exit 1
fi

required_backup_domains=(
  root
  file
  database
  sharedpref
  external
  device_root
  device_file
  device_database
  device_sharedpref
)
for domain in "${required_backup_domains[@]}"; do
  exclusion_count="$(
    rg --count "<exclude[[:space:]]+domain=\"$domain\"[[:space:]]+path=\"\\.\"[[:space:]]*/>" \
      "$DATA_EXTRACTION_RULES" || true
  )"
  if [[ "$exclusion_count" != "2" ]]; then
    echo "Android backup rules must exclude $domain from cloud and device transfer." >&2
    exit 1
  fi
done

if rg -n '^\s+(firebase_|sentry|http:|dio:|amplitude_|mixpanel_)' \
  "$PROJECT_DIR/pubspec.yaml"; then
  echo "Banned network/analytics dependency found in pubspec.yaml." >&2
  exit 1
fi

merged_manifests=()
known_manifests=(
  "$PROJECT_DIR/build/app/intermediates/merged_manifests/release/processReleaseManifest/AndroidManifest.xml"
  "$PROJECT_DIR/build/app/intermediates/merged_manifest/release/processReleaseMainManifest/AndroidManifest.xml"
  "$PROJECT_DIR/build/app/intermediates/packaged_manifests/release/processReleaseManifestForPackage/AndroidManifest.xml"
)
for manifest in "${known_manifests[@]}"; do
  [[ -f "$manifest" ]] && merged_manifests+=("$manifest")
done

intermediates="$PROJECT_DIR/build/app/intermediates"
if [[ -d "$intermediates" ]]; then
  while IFS= read -r manifest; do
    merged_manifests+=("$manifest")
  done < <(
    find "$intermediates" -type f -name AndroidManifest.xml -ipath '*/release/*' -print |
      sort -u
  )
fi

merged_count=0
while IFS= read -r manifest; do
  [[ -z "$manifest" ]] && continue
  audit_manifest_permissions "$manifest" "Android merged release"
  audit_manifest_backup_policy "$manifest" "Android merged release"
  merged_count=$((merged_count + 1))
done < <(printf '%s\n' "${merged_manifests[@]}" | sort -u)

if [[ "$merged_count" -eq 0 ]]; then
  if [[ "$REQUIRE_MERGED" == "1" ]]; then
    echo "Merged release manifest required but none was found; refusing a source-only pass." >&2
    exit 1
  fi
  echo "Offline source audit passed; merged release manifest not requested."
else
  echo "Offline release audit passed across $merged_count merged manifest(s)."
fi
